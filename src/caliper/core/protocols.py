from __future__ import annotations

from typing import AsyncIterator, Protocol, runtime_checkable

from caliper.core.models import Approval, Checkpoint, Run, RunRequest, RunResult, Step


@runtime_checkable
class Store(Protocol):
    """SQLite today, PostgreSQL tomorrow. No SQL outside adapters."""

    def create_run(self, run: Run) -> None: ...
    def get_run(self, run_id: str) -> Run | None: ...
    def append_step(self, step: Step) -> None: ...
    def commit_step(self, run_id: str, seq: int) -> None: ...
    def last_committed(self, run_id: str) -> int: ...
    def put_checkpoint(self, cp: Checkpoint) -> None: ...
    def get_checkpoint(self, run_id: str) -> Checkpoint | None: ...
    def add_approval(self, ap: Approval) -> None: ...
    def pending_approvals(self, run_id: str | None = None) -> list[Approval]: ...


@runtime_checkable
class Queue(Protocol):
    async def submit(self, run_id: str) -> str: ...
    def consume(self) -> AsyncIterator[str]: ...


@runtime_checkable
class Orchestrator(Protocol):
    def run(self, req: RunRequest, store: Store) -> RunResult: ...


@runtime_checkable
class RunnerService(Protocol):
    """Shared by CLI and FastAPI; returns data, never prints."""

    def execute(self, req: RunRequest) -> RunResult: ...
